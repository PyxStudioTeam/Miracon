export function getLocale(value?: string | URL | null): SiteLocale {
  const localePath = value instanceof URL ? value.pathname : value;
  return localePath === 'el' || /^\/el(?:\/|$)/.test(localePath ?? '') ? 'el' : 'en';
}

export function getMessages(locale: SiteLocale): Messages {
  return messages[locale];
}

export function getProjectContactDescriptionLines(locale: SiteLocale): readonly string[] {
  return projectContactDescriptionLines[locale];
}

export function formatMessage(message: string, values: Record<string, string>): string {
  return message.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}

export function localizePath(path: string, locale: SiteLocale): string {
  const parsed = new URL(path, 'https://miracon.local');
  const neutralPath = parsed.pathname.replace(/^\/el(?=\/|$)/, '') || '/';
  const localizedPath = locale === 'el'
    ? neutralPath === '/' ? '/el/' : `/el${neutralPath}`
    : neutralPath;
  return `${localizedPath}${parsed.search}${parsed.hash}`;
}

export function oppositeLocale(locale: SiteLocale): SiteLocale {
  return locale === 'el' ? 'en' : 'el';
}
